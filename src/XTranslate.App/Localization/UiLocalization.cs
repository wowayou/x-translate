    public static UiLanguage Preference { get; private set; } = UiLanguage.Auto;
    public static event EventHandler? Changed;

    static UiLocalization()
    {
        if (Chinese.Count != English.Count || Chinese.Keys.Except(English.Keys, StringComparer.Ordinal).Any())
            throw new InvalidOperationException("UI localization catalogs are out of sync.");
    }

    public static void SetPreference(UiLanguage preference)
    {
        if (!Enum.IsDefined(preference)) preference = UiLanguage.Auto;
        if (Preference == preference) return;
        Preference = preference;
        Changed?.Invoke(null, EventArgs.Empty);
    }

    public static string Get(string key)
    {
        var catalog = EffectiveLanguage == UiLanguage.English ? English : Chinese;
        return catalog.TryGetValue(key, out var value) ? value : $"[{key}]";
    }

    public static string Format(string key, params object[] arguments) => string.Format(CultureInfo.CurrentCulture, Get(key), arguments);

    public static UiLanguage EffectiveLanguage => Preference switch
    {
        UiLanguage.English => UiLanguage.English,
        UiLanguage.SimplifiedChinese => UiLanguage.SimplifiedChinese,
        _ => CultureInfo.CurrentUICulture.Name.StartsWith("zh", StringComparison.OrdinalIgnoreCase)
            ? UiLanguage.SimplifiedChinese
            : UiLanguage.English
    };

    public static IReadOnlyCollection<string> Keys => Chinese.Keys.ToArray();
